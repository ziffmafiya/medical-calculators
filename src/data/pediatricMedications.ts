// Функция для поиска препарата
export const findMedication = (searchTerm: string): MedicationInfo | undefined => {
  const term = searchTerm.toLowerCase();
  return pediatricMedicationsDatabase.find(med => 
    med.name.toLowerCase().includes(term) ||
    med.category.toLowerCase().includes(term)
  );
};

// Функция для получения всех препаратов по категории
export const getMedicationsByCategory = (category: string): MedicationInfo[] => {
  return pediatricMedicationsDatabase.filter(med => 
    med.category.toLowerCase().includes(category.toLowerCase())
  );
};

// Функция для получения всех категорий
export const getAllCategories = (): string[] => {
  const categories = pediatricMedicationsDatabase.map(med => med.category);
  return [...new Set(categories)];
};
